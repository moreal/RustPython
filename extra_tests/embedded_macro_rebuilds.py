#!/usr/bin/env python3
"""Exercise Cargo's dependency tracking for embedded Python inputs.

This host-side driver builds an independent Rust consumer without a build script.
The consumer decodes real macro-generated bytecode and prints its string constants.
Only Python inputs change between incremental builds; Rust, manifest, lockfile,
and Cargo caches are preserved. Use --output to retain all artifacts and -vv logs.
"""

import argparse
import hashlib
import json
import os
import shlex
import shutil
import subprocess
import sys
import time
from pathlib import Path

RUST = r"""
use rustpython_compiler_core::{bytecode::{BasicBag, ConstantData}, frozen::{FrozenCodeObject, FrozenLib}};
use rustpython_derive::{py_compile, py_freeze};

pub(crate) fn print_code(name: &str, code: FrozenCodeObject<impl AsRef<[u8]>>) {
    let decoded = code.decode(BasicBag);
    let markers: Vec<_> = decoded.constants.iter().filter_map(|constant| {
        match constant {
            ConstantData::Str { value } => Some(value.as_str().unwrap()),
            _ => None,
        }
    }).collect();
    println!("{}={}", name, markers.join("|"));
}

fn print_lib(name: &str, lib: &FrozenLib) {
    let mut modules: Vec<_> = lib.decode().collect();
    modules.sort_by_key(|(name, _)| *name);
    for (module_name, module) in modules {
        print_code(&format!("{name}.{module_name}"), module.code);
    }
}

static FROZEN_FILE: &FrozenLib = py_freeze!(file = "assets/freeze input.py", crate_name = "rustpython_compiler_core");
static FROZEN_DIR: &FrozenLib = py_freeze!(dir = "assets/frozen lib", crate_name = "rustpython_compiler_core");
static FROZEN_SOURCE: &FrozenLib = py_freeze!(source = "marker = 'inline_freeze'", crate_name = "rustpython_compiler_core");

pub fn run() {
    print_code("compile", py_compile!(file = "assets/compile input.py", crate_name = "rustpython_compiler_core"));
    print_lib("freeze", FROZEN_FILE);
    print_lib("dir", FROZEN_DIR);
    print_code("source", py_compile!(source = "marker = 'inline_compile'", crate_name = "rustpython_compiler_core"));
    print_lib("source_lib", FROZEN_SOURCE);
    print_code("wrapper_arg", crate::macro_inputs::from_arg!("assets/wrapped input.py"));
    print_code("wrapper_definition", crate::macro_inputs::from_definition!());
    crate::included::run();
    // ABSOLUTE_PROBE
    // SYMLINK_PROBE
}
"""

MACROS = r"""
macro_rules! from_arg {
    ($path:literal) => { rustpython_derive::py_compile!(file = $path, crate_name = "rustpython_compiler_core") };
}
macro_rules! from_definition {
    () => { rustpython_derive::py_compile!(file = "definition input.py", crate_name = "rustpython_compiler_core") };
}
pub(crate) use {from_arg, from_definition};
"""


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def protected_files(consumer):
    paths = [consumer / "Cargo.toml", consumer / "Cargo.lock"]
    paths += sorted((consumer / "src").rglob("*.rs"))
    return {
        str(path.relative_to(consumer)): {
            "sha256": digest(path),
            "mtime_ns": path.stat().st_mtime_ns,
        }
        for path in paths
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--expect-stale",
        action="store_true",
        help="Assert the original bug instead of the fixed behavior",
    )
    args = parser.parse_args()
    repo = args.repo.resolve()
    output = args.output.resolve()
    if output.exists():
        parser.error(
            "--output must name a new directory; existing evidence is never overwritten"
        )
    output.mkdir(parents=True)
    consumer = output / "consumer with spaces"
    assets = consumer / "src/nested module/assets"
    manifest = f"""[package]
name = "embedded-input-probe"
version = "0.0.0"
edition = "2024"

[workspace]

[dependencies]
rustpython-derive = {{ path = {json.dumps(str(repo / "crates/derive"))} }}
rustpython-compiler-core = {{ path = {json.dumps(str(repo / "crates/compiler-core"))} }}

[profile.dev.package."*"]
opt-level = 3
"""
    write(consumer / "Cargo.toml", manifest)
    shutil.copyfile(repo / "Cargo.lock", consumer / "Cargo.lock")
    write(
        consumer / "src/main.rs",
        '#[path = "nested module/probe.rs"]\nmod probe;\nmod macro_inputs;\nmod included { include!("fragments/embedded.rs"); }\nfn main() { probe::run(); }\n',
    )
    write(consumer / "src/macro_inputs.rs", MACROS)
    write(
        consumer / "src/fragments/embedded.rs",
        'pub fn run() { crate::probe::print_code("included", rustpython_derive::py_compile!(file = "fragment.py", crate_name = "rustpython_compiler_core")); }\n',
    )
    initial = {
        "compile input.py": "compile_before",
        "freeze input.py": "freeze_before",
        "frozen lib/module.py": "dir_before",
        "frozen lib/pkg/__init__.py": "package_before",
        "frozen lib/pkg/child.py": "nested_before",
        "symlink target.py": "symlink_before",
        "absolute input.py": "absolute_before",
        "wrapped input.py": "wrapper_arg_before",
        "../../definition input.py": "wrapper_definition_before",
        "../../fragments/fragment.py": "included_before",
        "new symlink target.py": "retargeted",
    }
    for name, marker in initial.items():
        write(assets / name, f"marker = '{marker}'\n")
    write(assets / "frozen lib/badsyntax_optional.py", "this is invalid Python !!!\n")
    (assets / "frozen lib/badsyntax_encoding.py").write_bytes(b"marker = '\xff'\n")
    symlink = True
    try:
        (assets / "link.py").symlink_to("symlink target.py")
        (assets / "frozen lib/linked.py").symlink_to("../symlink target.py")
    except (OSError, NotImplementedError):
        symlink = False
        (assets / "link.py").unlink(missing_ok=True)
        (assets / "frozen lib/linked.py").unlink(missing_ok=True)
    rust = RUST.replace(
        "// SYMLINK_PROBE",
        'print_code("symlink", py_compile!(file = "assets/link.py", crate_name = "rustpython_compiler_core"));'
        if symlink
        else "",
    )
    rust = rust.replace(
        "// ABSOLUTE_PROBE",
        'print_code("absolute", py_compile!(file = '
        + json.dumps(str(assets / "absolute input.py"), ensure_ascii=False)
        + ', crate_name = "rustpython_compiler_core"));',
    )
    write(consumer / "src/nested module/probe.rs", rust)
    target = Path(os.environ.get("CARGO_TARGET_DIR", str(output / "target"))).resolve()
    env = dict(os.environ, CARGO_TARGET_DIR=str(target))
    report = {
        "repo": str(repo),
        "consumer": str(consumer),
        "target": str(target),
        "symlink_supported": symlink,
        "expect_stale": args.expect_stale,
        "builds": [],
        "checks": [],
    }

    def save():
        write(output / "report.json", json.dumps(report, indent=2) + "\n")

    def build(label, locked=True, expected_error=None):
        command = ["cargo", "build", "--offline", "-vv"]
        if locked:
            command.append("--locked")
        start = time.time()
        log_path = output / f"{label}.cargo.log"
        with log_path.open("w", encoding="utf-8") as stream:
            result = subprocess.run(
                command,
                cwd=consumer,
                env=env,
                stdout=stream,
                stderr=subprocess.STDOUT,
                text=True,
            )
        log = log_path.read_text(encoding="utf-8")
        entry = {
            "label": label,
            "command": command,
            "exit_code": result.returncode,
            "seconds": round(time.time() - start, 3),
            "freshness": [
                line.strip()
                for line in log.splitlines()
                if "embedded-input-probe" in line
                and ("Fresh " in line or "Dirty " in line or "Compiling " in line)
            ],
        }
        report["builds"].append(entry)
        save()
        if expected_error is not None:
            check(
                label, result.returncode != 0 and expected_error in log, expected_error
            )
            return None
        if result.returncode:
            print(log[-12000:], file=sys.stderr)
            raise RuntimeError(f"Cargo failed in {label}; see retained log")
        binary = (
            target
            / "debug"
            / (
                "embedded-input-probe.exe"
                if os.name == "nt"
                else "embedded-input-probe"
            )
        )
        run = subprocess.run(
            [str(binary)], cwd=consumer, capture_output=True, text=True, check=True
        )
        write(output / f"{label}.stdout", run.stdout)
        markers = dict(line.split("=", 1) for line in run.stdout.splitlines())
        depinfo = target / "debug/embedded-input-probe.d"
        if depinfo.exists():
            shutil.copyfile(depinfo, output / f"{label}.dep-info")
        entry["markers"] = markers
        entry["protected_files"] = protected_files(consumer)
        save()
        return markers

    failures = []

    def check(label, condition, detail):
        report["checks"].append({"label": label, "passed": condition, "detail": detail})
        if not condition:
            failures.append(label)
        print(f"{'PASS' if condition else 'FAIL'} {label}: {detail}", flush=True)
        save()

    baseline = build("00-initial", locked=False)
    protected = protected_files(consumer)
    report["protected_files_initial"] = protected
    report["input_files_initial"] = {
        str(path.relative_to(consumer)): digest(path)
        for path in sorted(consumer.rglob("*.py"))
    }
    check(
        "initial-values",
        baseline.get("compile") == "compile_before"
        and baseline.get("freeze.frozen") == "freeze_before"
        and baseline.get("dir.module") == "dir_before"
        and baseline.get("dir.pkg.child") == "nested_before",
        baseline,
    )
    unchanged = build("01-no-op")
    check(
        "no-op",
        unchanged == baseline
        and any(
            "Fresh embedded-input-probe" in line
            for line in report["builds"][-1]["freshness"]
        ),
        report["builds"][-1]["freshness"],
    )

    edits = [
        ("compile-file", "compile input.py", "compile", "compile_after"),
        ("freeze-file", "freeze input.py", "freeze.frozen", "freeze_after"),
        ("directory-file", "frozen lib/module.py", "dir.module", "dir_after"),
        (
            "nested-directory-file",
            "frozen lib/pkg/child.py",
            "dir.pkg.child",
            "nested_after",
        ),
        ("absolute-file", "absolute input.py", "absolute", "absolute_after"),
        ("macro-argument-file", "wrapped input.py", "wrapper_arg", "wrapper_arg_after"),
        (
            "macro-definition-file",
            "../../definition input.py",
            "wrapper_definition",
            "wrapper_definition_after",
        ),
        (
            "included-rust-file",
            "../../fragments/fragment.py",
            "included",
            "included_after",
        ),
    ]
    if symlink:
        edits.append(
            ("symlink-target", "symlink target.py", "symlink", "symlink_after")
        )
    edits.append(
        (
            "previously-skipped-file",
            "frozen lib/badsyntax_optional.py",
            "dir.badsyntax_optional",
            "valid_after",
        )
    )
    edits.append(
        (
            "previously-skipped-encoding",
            "frozen lib/badsyntax_encoding.py",
            "dir.badsyntax_encoding",
            "valid_encoding",
        )
    )
    for index, (label, relative, key, marker) in enumerate(edits, 2):
        time.sleep(1.1)  # Avoid timestamp-granularity ambiguity on incremental inputs.
        write(assets / relative, f"marker = '{marker}'\n")
        result = build(f"{index:02}-{label}")
        expected = baseline.get(key) if args.expect_stale else marker
        check(
            label,
            result.get(key) == expected,
            {
                "key": key,
                "expected": expected,
                "actual": result.get(key),
                "freshness": report["builds"][-1]["freshness"],
            },
        )
        status = "Fresh" if args.expect_stale else "Dirty"
        check(
            f"{label}-cargo-status",
            any(
                f"{status} embedded-input-probe" in line
                for line in report["builds"][-1]["freshness"]
            ),
            report["builds"][-1]["freshness"],
        )
        if symlink and label == "symlink-target":
            expected_link = baseline.get("dir.linked") if args.expect_stale else marker
            check(
                "directory-symlink-target",
                result.get("dir.linked") == expected_link,
                result.get("dir.linked"),
            )
        check(
            f"{label}-protected-files",
            protected_files(consumer) == protected,
            "Rust source, manifest and lockfile unchanged",
        )
        check(
            f"{label}-inline-source",
            result.get("source") == "inline_compile"
            and result.get("source_lib.frozen") == "inline_freeze",
            "source= controls unchanged",
        )

    if symlink:
        time.sleep(1.1)
        for link, target_name in [
            (assets / "link.py", "new symlink target.py"),
            (assets / "frozen lib/linked.py", "../new symlink target.py"),
        ]:
            link.unlink()
            link.symlink_to(target_name)
        retarget = build("19-symlink-retarget")
        report["symlink_retarget_boundary"] = {
            "discovered_without_other_change": retarget.get("symlink") == "retargeted",
            "freshness": report["builds"][-1]["freshness"],
        }
        print(
            f"BOUNDARY symlink-retarget: {report['symlink_retarget_boundary']}",
            flush=True,
        )
        check(
            "retarget-protected-files",
            protected_files(consumer) == protected,
            "Only Python-file symlinks were retargeted",
        )

    time.sleep(1.1)
    write(assets / "frozen lib/new_module.py", "marker = 'added_after'\n")
    addition = build("20-new-file-addition")
    report["new_file_boundary"] = {
        "discovered_without_other_change": "dir.new_module" in addition,
        "freshness": report["builds"][-1]["freshness"],
    }
    print(f"BOUNDARY new-file-addition: {report['new_file_boundary']}", flush=True)
    check(
        "addition-protected-files",
        protected_files(consumer) == protected,
        "Only a new Python file was added",
    )
    time.sleep(1.1)
    (assets / "frozen lib/module.py").unlink()
    removal = build("21-known-file-removal")
    check(
        "known-file-removal",
        ("dir.module" in removal) == args.expect_stale,
        {
            "still_present": "dir.module" in removal,
            "freshness": report["builds"][-1]["freshness"],
        },
    )
    if not args.expect_stale:
        check(
            "addition-discovered-on-recompile",
            removal.get("dir.new_module") == "added_after",
            removal.get("dir.new_module"),
        )
        if symlink:
            check(
                "retarget-discovered-on-recompile",
                removal.get("symlink") == "retargeted"
                and removal.get("dir.linked") == "retargeted",
                removal,
            )
    check(
        "removal-protected-files",
        protected_files(consumer) == protected,
        "Only a known Python file was removed",
    )
    final = build("22-final-no-op")
    check(
        "final-no-op",
        final == removal
        and any(
            "Fresh embedded-input-probe" in line
            for line in report["builds"][-1]["freshness"]
        ),
        report["builds"][-1]["freshness"],
    )
    if not args.expect_stale:
        time.sleep(1.1)
        write(assets / "compile input.py", "this is invalid Python !!!\n")
        build(
            "23-syntax-error",
            expected_error="Python compile error from assets/compile input.py:",
        )
        (assets / "compile input.py").unlink()
        build("24-missing-file", expected_error="Error reading file")
        check(
            "error-cases-protected-files",
            protected_files(consumer) == protected,
            "Only Python input content or existence changed",
        )
    if os.name == "posix":
        cwd = output / os.fsdecode(b"non-utf8-\xff")
        write(
            cwd / "src/main.rs",
            '#[path = "nested/probe.rs"]\nmod probe;\nmod macro_inputs;\nfn main() { probe::run(); }\n',
        )
        write(cwd / "src/macro_inputs.rs", MACROS)
        write(cwd / "src/definition input.py", "marker = 'definition'\n")
        write(cwd / "src/nested/assets/wrapped input.py", "marker = 'argument'\n")
        write(cwd / "src/nested/assets/input.py", "marker = 'valid'\n")
        write(
            cwd / "src/nested/probe.rs",
            r"""
use rustpython_derive::{py_compile, py_freeze};
use rustpython_compiler_core::bytecode::{BasicBag, ConstantData};
static LIB: &rustpython_compiler_core::frozen::FrozenLib = py_freeze!(dir = "assets", crate_name = "rustpython_compiler_core");
pub fn run() {
    let code = py_compile!(file = "assets/input.py", crate_name = "rustpython_compiler_core");
    for value in code.decode(BasicBag).constants.iter() {
        if let ConstantData::Str { value } = value { println!("non_utf8_marker={}", value.as_str().unwrap()); }
    }
    let _ = py_freeze!(file = "assets/input.py", crate_name = "rustpython_compiler_core");
    let _ = LIB;
    let _ = crate::macro_inputs::from_definition!();
    let _ = crate::macro_inputs::from_arg!("assets/wrapped input.py");
    println!("non_utf8_ok");
}
""",
        )
        line = next(
            line
            for line in (output / "00-initial.cargo.log").read_text().splitlines()
            if "rustc --crate-name embedded_input_probe " in line
        )
        rustc_args = shlex.split(line.split("Running `", 1)[1].rsplit("`", 1)[0])
        binary = output / "non-utf8-probe"
        command = [
            "rustc",
            "--edition=2024",
            "--crate-name",
            "non_utf8_probe",
            "src/main.rs",
            "--emit=dep-info,link",
            "-o",
            "../non-utf8-probe",
        ]
        for index, arg in enumerate(rustc_args):
            if arg in ["--extern", "-L"]:
                command.extend(rustc_args[index : index + 2])
        result = subprocess.run(
            command, cwd=cwd, env=env, capture_output=True, text=True
        )
        write(output / "non-utf8-path.log", result.stdout + result.stderr)
        report["non_utf8_path"] = {
            "command": command,
            "cwd": str(cwd),
            "exit_code": result.returncode,
        }
        check(
            "non-utf8-ancestor",
            result.returncode == 0,
            {"exit_code": result.returncode},
        )
        if result.returncode == 0:
            run = subprocess.run(
                [str(binary)], capture_output=True, text=True, check=True
            )
            check(
                "non-utf8-runtime",
                run.stdout == "non_utf8_marker=valid\nnon_utf8_ok\n",
                run.stdout.strip(),
            )
            dep_info = (output / "non-utf8-probe.d").read_bytes()
            check(
                "non-utf8-tracking-boundary",
                b"assets/input.py" not in dep_info,
                "Python input is absent from rustc dep-info",
            )
            if shutil.which("make"):
                makefile = output / "non-utf8.mk"
                write(
                    makefile,
                    "../non-utf8-probe: src/main.rs\n\t"
                    + shlex.join(command)
                    + "\n-include ../non-utf8-probe.d\n",
                )
                time.sleep(1.1)
                write(cwd / "src/nested/assets/input.py", "marker = 'changed'\n")
                make = subprocess.run(
                    ["make", "-f", str(makefile)],
                    cwd=cwd,
                    env=env,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.STDOUT,
                )
                write(
                    output / "non-utf8-make.log", make.stdout.decode("utf-8", "replace")
                )
                after = subprocess.run(
                    [str(binary)], capture_output=True, text=True, check=True
                )
                check(
                    "non-utf8-stale-boundary",
                    make.returncode == 0 and after.stdout == run.stdout,
                    "Dep-info-driven make keeps the stale marker after a Python-only edit",
                )
            else:
                report["non_utf8_make"] = {"skipped": "make is not installed"}
    else:
        report["non_utf8_path"] = {"skipped": "Requires Unix byte-oriented filenames"}
    report["failures"] = failures
    report["status"] = "failed" if failures else "passed"
    save()
    print(f"Evidence: {output}")
    return bool(failures)


if __name__ == "__main__":
    sys.exit(main())
